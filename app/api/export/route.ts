function formatForYouTube(item: any, sd: any, scenes: any[]): string {
  let text = `YOUTUBE VIDEO SCRIPT\n${'='.repeat(50)}\n\n`
  
  text += `TITLE: ${item.title}\n`
  text += `PLATFORM: YouTube\n`
  text += `TYPE: ${sd.video_type || 'Tutorial'}\n`
  text += `LENGTH: ${sd.total_duration_estimate || '8-12 minutes'}\n\n`
  
  if (sd.title_options?.length) {
    text += `TITLE OPTIONS:\n`
    sd.title_options.forEach((t: string, i: number) => {
      text += `  ${i + 1}. ${t}\n`
    })
    text += '\n'
  }
  
  text += `${'─'.repeat(50)}\n\n`
  
  // Script sections
  const sections = sd.sections || scenes
  if (sections?.length > 0) {
    sections.forEach((s: any, i: number) => {
      const name = s.name || s.block_label || `Section ${i + 1}`
      const duration = s.duration || (s.duration_seconds ? `${s.duration_seconds}s` : '')
      
      text += `[${name}${duration ? ` - ${duration}` : ''}]\n\n`
      text += `SCRIPT:\n${s.speaking_lines || s.script_text || ''}\n\n`
      
      if (s.visual_notes || s.visual_direction || s.visual) {
        text += `VISUALS:\n${s.visual_notes || s.visual_direction || s.visual}\n\n`
      }
      
      if (s.tips) {
        text += `PRO TIPS:\n${s.tips}\n\n`
      }
      
      text += `${'─'.repeat(30)}\n\n`
    })
  }
  
  // Thumbnail concept
  if (sd.thumbnail_concept) {
    text += `THUMBNAIL CONCEPT:\n${sd.thumbnail_concept}\n\n`
  }
  
  // SEO metadata
  if (sd.description) {
    text += `DESCRIPTION:\n${sd.description}\n\n`
  }
  
  if (sd.tags?.length) {
    text += `TAGS:\n${sd.tags.join(', ')}\n\n`
  }
  
  text += `${'='.repeat(50)}\n`
  text += `Ready to film! 🎬\n`
  
  return text
}

function formatForGoogleDocs(item: any, sd: any, scenes: any[]): string {
  // Returns HTML that pastes well into Google Docs
  return formatAsHTML(item, sd, scenes, item.content_type)
}

async function generatePDF(html: string): Promise<Buffer> {
  const browser = await chromium.launch({ headless: true })
  const context = await browser.newContext()
  const page = await context.newPage()
  
  await page.setContent(html, { waitUntil: 'networkidle' })
  
  const pdfBuffer = await page.pdf({
    format: 'A4',
    printBackground: true,
    margin: { top: '1in', right: '1in', bottom: '1in', left: '1in' }
  })
  
  await browser.close()
  
  return Buffer.from(pdfBuffer)
}