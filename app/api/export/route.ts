/**
 * POST /api/export — Export content in various formats
 * 
 * Formats:
 * - txt: Plain text (default)
 * - pdf: PDF document with formatting
 * - gdoc: Create Google Doc and return URL
 * - youtube: YouTube creator format (script + thumbnail)
 * 
 * Requires authentication.
 */
import { NextRequest, NextResponse } from 'next/server'
import { createClient } from '@/lib/supabase/server'
import { chromium } from 'playwright'

export const maxDuration = 60

interface ExportRequest {
  itemId: string
  format: 'txt' | 'pdf' | 'gdoc' | 'youtube'
}

export async function POST(req: NextRequest) {
  const supabase = await createClient()
  const { data: { user } } = await supabase.auth.getUser()
  if (!user) {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
  }

  const { itemId, format = 'txt' }: ExportRequest = await req.json().catch(() => ({}))

  if (!itemId) {
    return NextResponse.json({ error: 'itemId required' }, { status: 400 })
  }

  try {
    // Fetch content item
    const { data: item, error } = await supabase
      .from('content_items')
      .select('*')
      .eq('id', itemId)
      .eq('user_id', user.id)
      .single()

    if (error || !item) {
      return NextResponse.json({ error: 'Content not found' }, { status: 404 })
    }

    const sd = item.script_data || {}
    const scenes = sd.scenes || []
    const contentType = item.content_type

    switch (format) {
      case 'txt': {
        const text = formatAsText(item, sd, scenes)
        return NextResponse.json({
          format: 'txt',
          filename: `${item.title || 'content'}.txt`,
          content: text,
          mimeType: 'text/plain',
        })
      }

      case 'pdf': {
        const html = formatAsHTML(item, sd, scenes, contentType)
        const pdfBuffer = await generatePDF(html)
        
        // Return as base64 for client download
        return NextResponse.json({
          format: 'pdf',
          filename: `${item.title || 'content'}.pdf`,
          content: pdfBuffer.toString('base64'),
          mimeType: 'application/pdf',
          base64: true,
        })
      }

      case 'youtube': {
        const youtubeFormat = formatForYouTube(item, sd, scenes)
        return NextResponse.json({
          format: 'txt',
          filename: `${item.title || 'video'} - YouTube Script.txt`,
          content: youtubeFormat,
          mimeType: 'text/plain',
        })
      }

      case 'gdoc': {
        // For now, return the content formatted for Google Docs
        // Full Google Docs API integration would require OAuth setup
        const gdocFormat = formatForGoogleDocs(item, sd, scenes)
        return NextResponse.json({
          format: 'gdoc-ready',
          filename: `${item.title || 'content'}`,
          content: gdocFormat,
          instructions: 'Copy this content and paste into Google Docs',
          mimeType: 'text/html',
        })
      }

      default:
        return NextResponse.json({ error: 'Unsupported format' }, { status: 400 })
    }

  } catch (err: any) {
    console.error('[Export] Failed:', err)
    return NextResponse.json({ error: err.message }, { status: 500 })
  }
}

function formatAsText(item: any, sd: any, scenes: any[]): string {
  let text = `${item.title}\n${'='.repeat(item.title.length)}\n\n`
  
  if (item.hook) {
    text += `HOOK: "${item.hook}"\n\n`
  }

  if (scenes.length > 0) {
    scenes.forEach((s: any, i: number) => {
      const label = s.block_label || `Scene ${s.scene_number || i + 1}`
      const duration = s.duration_seconds ? ` (${s.duration_seconds}s)` : ''
      text += `[${label}${duration}]\n`
      text += `${s.script_text || s.voiceover || ''}\n`
      if (s.visual_direction || s.visual) {
        text += `\nVisual: ${s.visual_direction || s.visual}\n`
      }
      if (s.on_screen_text) {
        text += `On-screen: "${s.on_screen_text}"\n`
      }
      text += '\n'
    })
  } else if (sd.headline) {
    text += `${sd.headline}\n\n${sd.primaryText || sd.body || ''}\n`
  } else if (sd.caption) {
    text += `${sd.caption}\n`
  }

  if (sd.hashtags?.length) {
    text += `\nHASHTAGS:\n${sd.hashtags.join(' ')}\n`
  }

  if (sd.cta || item.cta) {
    text += `\nCTA: ${sd.cta || item.cta}\n`
  }

  text += `\n---\nGenerated by Creative Studio\n${new Date().toLocaleDateString()}`
  
  return text
}

